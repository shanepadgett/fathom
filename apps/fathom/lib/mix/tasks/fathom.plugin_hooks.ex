defmodule Mix.Tasks.Fathom.PluginHooks do
  @shortdoc "Collects the colocated hooks of bundled plugins for app.js"
  @moduledoc """
  Writes `assets/js/plugin_hooks.js`, which merges the colocated LiveView
  hooks of every compiled dependency (bundled plugins and libraries) so
  `app.js` can register them without naming a plugin. Run after `compile`;
  the development esbuild watcher runs it through `watch/1`.
  """
  use Mix.Task

  @target Path.expand("../../../assets/js/plugin_hooks.js", __DIR__)

  @impl true
  def run(_args), do: write()

  @doc "Writes the hooks file, then runs the esbuild watcher with `args`."
  def watch(args) do
    write()
    Esbuild.install_and_run(:fathom, args)
  end

  defp write do
    apps =
      Path.join(Mix.Project.build_path(), "phoenix-colocated/*/index.js")
      |> Path.wildcard()
      |> Enum.map(&(&1 |> Path.dirname() |> Path.basename()))
      |> Enum.reject(&(&1 == "fathom"))
      |> Enum.sort()

    imports =
      apps
      |> Enum.with_index()
      |> Enum.map(fn {app, i} ->
        ~s(import {hooks as h#{i}} from "phoenix-colocated/#{app}"\n)
      end)

    spread = Enum.map_join(0..(length(apps) - 1)//1, ", ", &"...h#{&1}")

    contents = [
      "// Generated by `mix fathom.plugin_hooks`; do not edit.\n",
      imports,
      "export const hooks = {#{spread}}\n"
    ]

    if File.read(@target) != {:ok, IO.iodata_to_binary(contents)},
      do: File.write!(@target, contents)
  end
end
